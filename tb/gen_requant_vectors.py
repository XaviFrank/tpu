#!/usr/bin/env python3
"""Golden-vector generator for tb_requant (spec section 6).

Independent Python implementation of the requant math (ReLU -> scale ->
round-half-up -> arithmetic shift -> saturate). Python's unbounded ints
and floor-semantics >> make this an exact reference with no width
bookkeeping. Regenerate with:  python tb/gen_requant_vectors.py
Output: tb/requant_vectors.memh, one 64-bit hex word per vector:
  [63:32] acc (int32, two's complement)
  [31:16] scale_mult (int16)
  [15:11] shift_amt (0..31)
  [10]    relu_en
  [9:8]   unused (0)
  [7:0]   expected out (int8, two's complement)
Deterministic: fixed seed. Committed alongside the .memh so regression
never depends on Python being installed.
"""

import random

random.seed(20260715)

VECS = []


def golden(acc, relu_en, scale, shift):
    x = acc
    if relu_en and x < 0:
        x = 0
    p = x * scale
    if shift > 0:
        p += 1 << (shift - 1)          # round-half-up bias
    y = p >> shift                     # python >> on ints is floor: arithmetic
    if y > 127:
        y = 127
    if y < -128:
        y = -128
    return y


def add(acc, relu_en, scale, shift):
    VECS.append((acc, relu_en, scale, shift, golden(acc, relu_en, scale, shift)))


# --- directed cases (spec section 6) --------------------------------
add(1000, 0, 256, 8)          # mid-range, no clipping (out = 1000 -> clip? 1000>127 -> 127)
add(100, 0, 256, 8)           # mid-range, genuinely unclipped (out = 100)
add(127, 0, 256, 8)           # exact +127 boundary, must NOT clip
add(128, 0, 256, 8)           # first value past +127, must clip to 127
add(-128, 0, 256, 8)          # exact -128 boundary, must NOT clip
add(-129, 0, 256, 8)          # first value past -128, must clip to -128
add(2**31 - 1, 0, 32767, 0)   # max acc, shift=0 (no bias path), hard + clip
add(-(2**31), 0, 32767, 0)    # min acc, hard - clip
add(-5000, 1, 256, 8)         # ReLU on: negative zeroed
add(-5000, 0, 256, 8)         # same value, ReLU off: negative result (clips -)
add(50, 1, 256, 8)            # ReLU on: positive passes unchanged
add(1, 0, 1, 1)               # +0.5 rounds up to 1
add(-1, 0, 1, 1)              # -0.5 rounds up to 0 (round-half-up)
add(3, 0, 1, 1)               # 1.5 rounds to 2
add(0, 1, 32767, 31)          # zero in, zero out, extreme shift
add(123, 0, 1, 0)             # identity path: scale 1, shift 0

# --- seeded random sweep ---------------------------------------------
for _ in range(48):
    acc = random.randint(-(2**31), 2**31 - 1)
    scale = random.randint(1, 32767)
    shift = random.randint(0, 31)
    relu = random.randint(0, 1)
    add(acc, relu, scale, shift)

with open("tb/requant_vectors.memh", "w") as f:
    f.write("// generated by tb/gen_requant_vectors.py - do not hand-edit\n")
    for acc, relu, scale, shift, exp in VECS:
        word = (
            ((acc & 0xFFFFFFFF) << 32)
            | ((scale & 0xFFFF) << 16)
            | ((shift & 0x1F) << 11)
            | ((relu & 1) << 10)
            | (exp & 0xFF)
        )
        f.write(f"{word:016x}\n")

print(f"wrote {len(VECS)} vectors to tb/requant_vectors.memh")
