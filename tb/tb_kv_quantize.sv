`timescale 1ns / 1ps
//====================================================================
// tb_kv_quantize - the write path from real INT8 K/V through rotation
// to a packed cache line, bit-exact.
//
//   Four chains, the asymmetric format crossed with both rotations:
//
//     A  mode 0 Hadamard -> QBITS 3, QJL off   V   13 words
//     B  mode 0 Hadamard -> QBITS 2, QJL on    K   14 words
//     C  mode 1 dense Pi -> QBITS 3, QJL off   V   13 words
//     D  mode 1 dense Pi -> QBITS 2, QJL on    K   14 words
//
//   Each chain carries the codebook FITTED TO ITS OWN ROTATION MODE.
//   Crossing them would charge one mode for a distribution mismatch
//   that has nothing to do with the rotation, which is why CB_PATH is
//   per-instance rather than a global.
//
//   The rotate and quantize stages are wired together rather than the
//   quantizer being fed pre-rotated data, so an interface mismatch
//   between the two has somewhere to show up.
//
//   Q5 is the check that would catch a quantizer that had collapsed:
//   every codeword must actually be used. A quantizer emitting only
//   the middle levels would still produce a plausible norm and a
//   plausible packed word, and a pure value compare against a golden
//   generated by the same collapsed logic would not notice.
//====================================================================
module tb_kv_quantize;

    localparam int N = 128;

    logic clk = 1'b0;
    logic rst_n = 1'b0;
    always #5 clk = ~clk;

    integer errors = 0;

    logic [7:0] x_k [N];
    logic [7:0] x_v [N];

    // Sized to the exact word count of each format - 13 for the
    // QJL-free V line, 14 for K. Reading a 13-word file into a 16-word
    // array warns, and a warning that is always present is a warning
    // nobody reads when the file really is short.
    logic [31:0] exp_a [13], exp_b [14], exp_c [13], exp_d [14];
    logic [31:0] got_a [16], got_b [16], got_c [16], got_d [16];

    initial begin
        $readmemh("tb/kv_x_k.memh", x_k);
        $readmemh("tb/kv_x_v.memh", x_v);
        $readmemh("tb/kv_q_exp_m0_v.memh", exp_a);
        $readmemh("tb/kv_q_exp_m0_k.memh", exp_b);
        $readmemh("tb/kv_q_exp_m1_v.memh", exp_c);
        $readmemh("tb/kv_q_exp_m1_k.memh", exp_d);
    end

    //----------------------------------------------------------------
    // Four chains. Explicit rather than generated: the parameters
    // differ in width AND in string, and dull repetition beats a
    // clever generate that has to be debugged through elaboration.
    //----------------------------------------------------------------
    logic [7:0]         ba [N], bb [N], bc [N], bd [N];
    logic               sa, sb, sc, sd;
    logic               ra_en, rb_en, rc_en, rd_en;
    logic [6:0]         ra_ad, rb_ad, rc_ad, rd_ad;
    logic signed [7:0]  ra_dt, rb_dt, rc_dt, rd_dt;
    logic               ya_v, yb_v, yc_v, yd_v;
    logic [6:0]         ya_i, yb_i, yc_i, yd_i;
    logic signed [23:0] ya_d, yb_d, yc_d, yd_d;
    logic               ra_bs, rb_bs, rc_bs, rd_bs;
    logic               ra_dn, rb_dn, rc_dn, rd_dn;
    logic               qa_bs, qb_bs, qc_bs, qd_bs;
    logic               wa_v, wb_v, wc_v, wd_v;
    logic [4:0]         wa_i, wb_i, wc_i, wd_i;
    logic [31:0]        wa_d, wb_d, wc_d, wd_d;
    logic               da, db, dc, dd;

    always_ff @(posedge clk) ra_dt <= ba[ra_ad];
    always_ff @(posedge clk) rb_dt <= bb[rb_ad];
    always_ff @(posedge clk) rc_dt <= bc[rc_ad];
    always_ff @(posedge clk) rd_dt <= bd[rd_ad];

    always_ff @(posedge clk) if (wa_v) got_a[wa_i] <= wa_d;
    always_ff @(posedge clk) if (wb_v) got_b[wb_i] <= wb_d;
    always_ff @(posedge clk) if (wc_v) got_c[wc_i] <= wc_d;
    always_ff @(posedge clk) if (wd_v) got_d[wd_i] <= wd_d;

    kv_rotate #(.N(N), .ROT_MODE(0)) rot_a (
        .clk(clk), .rst_n(rst_n), .start(sa), .busy(ra_bs),
        .x_rd_en(ra_en), .x_rd_addr(ra_ad), .x_rd_data(ra_dt),
        .y_valid(ya_v), .y_idx(ya_i), .y_out(ya_d), .done(ra_dn));

    kv_quantize #(.N(N), .QBITS(3), .QJL_EN(0),
                  .CB_PATH("rtl/kv_cb_m0_b3.memh")) qnt_a (
        .clk(clk), .rst_n(rst_n), .in_valid(ya_v), .in_data(ya_d),
        .busy(qa_bs), .w_valid(wa_v), .w_idx(wa_i), .w_data(wa_d), .done(da));

    kv_rotate #(.N(N), .ROT_MODE(0)) rot_b (
        .clk(clk), .rst_n(rst_n), .start(sb), .busy(rb_bs),
        .x_rd_en(rb_en), .x_rd_addr(rb_ad), .x_rd_data(rb_dt),
        .y_valid(yb_v), .y_idx(yb_i), .y_out(yb_d), .done(rb_dn));

    kv_quantize #(.N(N), .QBITS(2), .QJL_EN(1),
                  .CB_PATH("rtl/kv_cb_m0_b2.memh")) qnt_b (
        .clk(clk), .rst_n(rst_n), .in_valid(yb_v), .in_data(yb_d),
        .busy(qb_bs), .w_valid(wb_v), .w_idx(wb_i), .w_data(wb_d), .done(db));

    kv_rotate #(.N(N), .ROT_MODE(1)) rot_c (
        .clk(clk), .rst_n(rst_n), .start(sc), .busy(rc_bs),
        .x_rd_en(rc_en), .x_rd_addr(rc_ad), .x_rd_data(rc_dt),
        .y_valid(yc_v), .y_idx(yc_i), .y_out(yc_d), .done(rc_dn));

    kv_quantize #(.N(N), .QBITS(3), .QJL_EN(0),
                  .CB_PATH("rtl/kv_cb_m1_b3.memh")) qnt_c (
        .clk(clk), .rst_n(rst_n), .in_valid(yc_v), .in_data(yc_d),
        .busy(qc_bs), .w_valid(wc_v), .w_idx(wc_i), .w_data(wc_d), .done(dc));

    kv_rotate #(.N(N), .ROT_MODE(1)) rot_d (
        .clk(clk), .rst_n(rst_n), .start(sd), .busy(rd_bs),
        .x_rd_en(rd_en), .x_rd_addr(rd_ad), .x_rd_data(rd_dt),
        .y_valid(yd_v), .y_idx(yd_i), .y_out(yd_d), .done(rd_dn));

    kv_quantize #(.N(N), .QBITS(2), .QJL_EN(1),
                  .CB_PATH("rtl/kv_cb_m1_b2.memh")) qnt_d (
        .clk(clk), .rst_n(rst_n), .in_valid(yd_v), .in_data(yd_d),
        .busy(qd_bs), .w_valid(wd_v), .w_idx(wd_i), .w_data(wd_d), .done(dd));

    //----------------------------------------------------------------
    // done is a one-cycle pulse and the four chains finish at
    // different times (QBITS changes S_THR's length, QJL_EN adds a
    // second square root), so latch rather than waiting on a
    // coincidence that never happens.
    //----------------------------------------------------------------
    logic fa, fb, fc, fd;
    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            fa <= 1'b0; fb <= 1'b0; fc <= 1'b0; fd <= 1'b0;
        end else begin
            if (da) fa <= 1'b1;
            if (db) fb <= 1'b1;
            if (dc) fc <= 1'b1;
            if (dd) fd <= 1'b1;
        end
    end

    integer i;

    task automatic load_all;
        integer j;
        begin
            for (j = 0; j < N; j = j + 1) begin
                ba[j] = x_v[j];   // chain A quantizes V
                bb[j] = x_k[j];   // chain B quantizes K
                bc[j] = x_v[j];
                bd[j] = x_k[j];
            end
        end
    endtask

    task automatic cmp(input [63:0] tag, input integer nw, input integer sel);
        integer j;
        logic [31:0] g, e;
        integer bad;
        begin
            bad = 0;
            for (j = 0; j < nw; j = j + 1) begin
                case (sel)
                    0: begin g = got_a[j]; e = exp_a[j]; end
                    1: begin g = got_b[j]; e = exp_b[j]; end
                    2: begin g = got_c[j]; e = exp_c[j]; end
                    default: begin g = got_d[j]; e = exp_d[j]; end
                endcase
                if (g !== e) begin
                    bad = bad + 1;
                    if (bad <= 4)
                        $display("Error: %0s word %0d got %08h exp %08h",
                                 tag, j, g, e);
                end
            end
            errors = errors + bad;
            $display("  %0s  %0d/%0d words exact", tag, nw - bad, nw);
        end
    endtask

    // Q5: every codeword must appear somewhere in the packed indices.
    task automatic used(input [63:0] tag, input integer qbits,
                        input integer nwq, input integer sel);
        integer j, b, v, nlev, seen, miss;
        logic [31:0] wrd;
        logic [383:0] bits;
        begin
            bits = '0;
            for (j = 0; j < nwq; j = j + 1) begin
                case (sel)
                    0: wrd = got_a[j];
                    1: wrd = got_b[j];
                    2: wrd = got_c[j];
                    default: wrd = got_d[j];
                endcase
                bits = (bits << 32) | {352'b0, wrd};
            end
            nlev = 1 << qbits;
            seen = 0;
            for (j = 0; j < N; j = j + 1) begin
                v = 0;
                for (b = 0; b < qbits; b = b + 1)
                    v = (v << 1) | bits[(N-1-j)*qbits + (qbits-1-b)];
                seen = seen | (1 << v);
            end
            miss = 0;
            for (j = 0; j < nlev; j = j + 1)
                if (((seen >> j) & 1) == 0) miss = miss + 1;
            if (miss != 0) begin
                errors = errors + 1;
                $display("Error: %0s %0d of %0d codewords never used",
                         tag, miss, nlev);
            end else begin
                $display("  %0s  all %0d codewords used", tag, nlev);
            end
        end
    endtask

    initial begin
        sa = 0; sb = 0; sc = 0; sd = 0;
        repeat (4) @(negedge clk);
        rst_n = 1'b1;
        repeat (2) @(negedge clk);
        load_all();

        $display("=== kv_quantize: real K/V, rotate -> quantize -> pack ===");

        @(negedge clk); sa = 1; sb = 1; sc = 1; sd = 1;
        @(negedge clk); sa = 0; sb = 0; sc = 0; sd = 0;

        while (!(fa && fb)) @(posedge clk);
        @(posedge clk);
        $display("Q1/Q2 randomized Hadamard");
        cmp("Q1 m0 V", 13, 0);  used("Q1 m0 V", 3, 12, 0);
        cmp("Q2 m0 K", 14, 1);  used("Q2 m0 K", 2,  8, 1);

        while (!(fc && fd)) @(posedge clk);
        @(posedge clk);
        $display("Q3/Q4 dense Pi");
        cmp("Q3 m1 V", 13, 2);  used("Q3 m1 V", 3, 12, 2);
        cmp("Q4 m1 K", 14, 3);  used("Q4 m1 K", 2,  8, 3);

        if (errors == 0) $display("ALL TESTS PASSED");
        else             $display("FAILED with %0d errors", errors);
        $finish;
    end

    initial begin
        #6000000;
        $display("Error: timeout");
        $display("FAILED");
        $finish;
    end

endmodule
